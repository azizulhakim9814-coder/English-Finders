/**
 * Grammar item bank.
 *
 * Unlike the vocabulary tools, grammar has no dictionary to draw questions
 * from — a word row has a definition and a part of speech, but nothing about
 * sentence-level rules. There is no such dataset anywhere in this codebase, so
 * this is deliberately a small, hand-curated bank rather than a query. Every
 * item is a single sentence with one blank, four options and one unambiguous
 * correct answer — no item here depends on a British/American usage split or
 * a contested style rule, since a grammar drill that is itself debatable
 * teaches the wrong lesson.
 *
 * The bank covers A1–C2 with 60 items per level. It originally stopped at B1
 * on the grounds that some upper-level grammar carries genuine native-speaker
 * disagreement — but that is a property of specific *points*, not of levels.
 * The B2–C2 items here are drawn only from points that stay unambiguous
 * (passive voice, reported speech, real and unreal conditionals, relative
 * clauses, gerund/infinitive patterns, linking words, plus harder instances of
 * the original eight), and every item was checked for exactly one defensible
 * option: where an item had two acceptable answers (for example "If I was/were
 * you", or "will" vs "going to" for a prediction) it was rewritten or its
 * options changed rather than kept. Genuinely contested points — mixed
 * conditionals, subjunctive "that"-clauses, collective nouns with British/
 * American agreement splits — are still left out.
 *
 * 24 per level was chosen as double `GrammarQuiz::SESSION_LENGTH` (12), so a
 * full single-level session never repeats. 1.15.0 added 18 more per level
 * (the "Level test expansion" blocks at the end, same rules as above; C2
 * adds sentence-initial inversion, which is unambiguous) because the English
 * Level Test draws its grammar questions from this bank too: a learner who
 * retakes the test should mostly meet new sentences, and a Grammar Quiz
 * learner now gets three fresh sessions per level. 1.16.0 added 18 more per
 * level (the "1.16.0 expansion" blocks) for five fresh Grammar Quiz sessions
 * per level. Extending coverage means adding items here; nothing else in
 * either tool changes shape.
 *
 * @package EnglishFindersStudy
 */

