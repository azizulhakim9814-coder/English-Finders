<?php
/**
 * Add sense-level CEFR columns, and seed the first cross-checked batch.
 *
 * `wuc_words.cefr_level` tags one level per headword, but a headword is not
 * one word: "shed" is A2 as a garden building and C1 as "to shed light on."
 * Tagging the whole word C1 (as a word-level-only source would) makes the
 * badge wrong for the sense a beginner is actually looking up. This migration
 * gives `wuc_word_senses` its own `cefr_level`/`cefr_source` pair so a sense
 * can carry a level the headword itself does not.
 *
 * The seed data below is not the full CEFR bridge backlog -- it is the
 * specific set of (word, part_of_speech) pairs that were cross-checked
 * against the Octanove C1/C2 vocabulary profile (CC BY-SA 4.0) *and* against
 * this dictionary's own stored sense definitions, to rule out a part of
 * speech that still mixes a basic and an advanced sense (e.g. "wing" as noun
 * covers both a bird's wing and a political wing, so it was excluded rather
 * than guessed at). Only pairs where every stored sense under that part of
 * speech was judged consistent were kept. See the CEFR data-quality work
 * referenced in project memory for the full audit trail.
 *
 * @package EnglishFindersCore
 */

declare(strict_types=1);

namespace EnglishFindersCore\Database;

