		return self::TOPIC_LABELS[ $topic ] ?? $topic;
	}

	/**
	 * Items at one level, or every item when the level is empty.
	 *
	 * @return list<array{id:string,topic:string,level:string,prompt:string,options:list<string>,correct:int,explanation:string}>
	 */
	public static function by_level( string $level ): array {
		if ( '' === $level ) {
			return self::items();
		}

		return array_values(
			array_filter(
				self::items(),
				static fn ( array $item ): bool => $item['level'] === $level
			)
		);
	}

	/**
	 * Levels actually present in the bank, in CEFR order.
	 *
	 * Deliberately independent of `wuc_available_cefr_levels()` — that
	 * function reports which levels the *dictionary* has tagged words for,
	 * an entirely different dataset from this hand-authored bank.
	 *
	 * @return list<string>
	 */
	public static function available_levels(): array {
		$present = array();
		foreach ( self::items() as $item ) {
			$present[ $item['level'] ] = true;
		}

		return array_values(
			array_intersect(
				array( 'A1', 'A2', 'B1', 'B2', 'C1', 'C2' ),
				array_keys( $present )
			)
		);
	}
