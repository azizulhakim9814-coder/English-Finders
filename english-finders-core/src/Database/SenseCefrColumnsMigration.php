	public function version(): string {
		return '1.4.0';
	}

	public function description(): string {
		return 'Add cefr_level and cefr_source columns to word_senses, and seed a cross-checked sense-level backfill.';
	}

	public function up(): void {
		global $wpdb;

		$table = Schema::shared_table( 'word_senses' );

		foreach ( $this->columns() as $column => $definition ) {
			if ( $this->column_exists( $table, $column ) ) {
				continue;
			}
			// phpcs:ignore WordPress.DB.PreparedSQL.InterpolatedNotPrepared, WordPress.DB.DirectDatabaseQuery.SchemaChange
			$wpdb->query( "ALTER TABLE {$table} ADD COLUMN {$column} {$definition}" );
		}

		if ( ! $this->index_exists( $table, 'cefr_level' ) ) {
			// phpcs:ignore WordPress.DB.PreparedSQL.InterpolatedNotPrepared, WordPress.DB.DirectDatabaseQuery.SchemaChange
			$wpdb->query( "ALTER TABLE {$table} ADD INDEX cefr_level (cefr_level)" );
		}

		$this->seed();
	}

	/**
	 * Columns are safe to drop -- seed data can be regenerated by re-running
	 * this migration, and nothing else writes to these columns yet.
	 */
	public function down(): void {
		global $wpdb;

		$table = Schema::shared_table( 'word_senses' );

		foreach ( array_keys( $this->columns() ) as $column ) {
			if ( ! $this->column_exists( $table, $column ) ) {
				continue;
			}
			// phpcs:ignore WordPress.DB.PreparedSQL.InterpolatedNotPrepared, WordPress.DB.DirectDatabaseQuery.SchemaChange
			$wpdb->query( "ALTER TABLE {$table} DROP COLUMN {$column}" );
		}
	}

	/** @return array<string,string> */
	private function columns(): array {
		return array(
			'cefr_level'  => "varchar(2) NOT NULL DEFAULT ''",
			'cefr_source' => "varchar(16) NOT NULL DEFAULT ''",
		);
	}

	/**
	 * Tag every sense row sharing (word, part_of_speech) with the seeded
	 * level -- the template groups definitions by part of speech, so this is
	 * exactly the granularity a reader sees. Only rows whose word/POS pair
	 * exists are touched; a pair with no matching sense is a harmless no-op,
	 * not an error, since the source dataset and this dictionary were built
	 * independently.
	 */
	private function seed(): void {
		global $wpdb;

		$words_table  = Schema::shared_table( 'words' );
		$senses_table = Schema::shared_table( 'word_senses' );

		foreach ( $this->seed_data() as list( $word, $pos, $level ) ) {
			$word_id = (int) $wpdb->get_var(
				$wpdb->prepare(
					// phpcs:ignore WordPress.DB.PreparedSQL.InterpolatedNotPrepared
					"SELECT id FROM {$words_table} WHERE normalized = %s AND language = 'en'",
					$word
				)
			);
			if ( $word_id < 1 ) {
				continue;
			}
			$wpdb->query(
				$wpdb->prepare(
					// phpcs:ignore WordPress.DB.PreparedSQL.InterpolatedNotPrepared
					"UPDATE {$senses_table} SET cefr_level = %s, cefr_source = 'octanove', updated_at = %s WHERE word_id = %d AND part_of_speech = %s",
					$level,
					current_time( 'mysql', true ),
					$word_id,
					$pos
				)
			);
		}
	}

