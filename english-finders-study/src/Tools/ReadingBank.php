/**
 * Reading comprehension item bank.
 *
 * Like grammar, reading comprehension has no dataset anywhere in this
 * codebase to draw from — a dictionary row is a single word, not a passage.
 * So this is a small, hand-curated bank: each item is a short passage, one
 * comprehension question about it, four options and one unambiguous correct
 * answer.
 *
 * Every question is answerable directly from a sentence actually in the
 * passage — a detail-recall or a single-step inference, never a question that
 * depends on a reader's own interpretation or outside knowledge. A "what do
 * you think" reading question is not gradable, and grading it as if it were
 * would teach the wrong lesson, the same reasoning `GrammarBank` applies to
 * contested style rules.
 *
 * All six CEFR levels are covered, unlike `GrammarBank`'s A1–B1 cap — and
 * deliberately so, not an oversight. Grammar caps at B1 because the higher-
 * level *rules themselves* (mixed conditionals, the subjunctive, reported
 * speech) carry genuine native-speaker disagreement, so a B2+ grammar item
 * risks teaching a contested answer as fact. Reading comprehension has no
 * equivalent problem: a passage's vocabulary and sentence structure can scale
 * all the way to C2 while the question stays a plain, directly-supported
 * detail or inference — sophistication of language is not the same thing as
 * ambiguity of the question asked. What stays fixed at every level is the
 * discipline above: never a question the passage doesn't settle outright.
 *
 * Size: 36 passages per level since 1.16.0 (6 until 1.15.0, then 24). The
 * English Level Test draws its reading questions from here too, and with 6
 * per level a learner retaking the test met the same passages almost every
 * time. 36 covers more than three full ten-passage Reading Quiz sessions per
 * level before anything repeats. Every explanation quotes its passage word for word
 * (an ellipsis marks a cut), which tests/test_level_test.php checks.
 *
 * @package EnglishFindersStudy
 */

